# --- the GNSS-denied mode this board exists for ---------------------------
# THE SoOP FIX ARRIVES AS A SECOND GPS, NOT AS ExternalNav. That decision was made by
# measurement in sitl/, and it reversed the obvious choice.
#
# ExternalNav (VISION_POSITION_ESTIMATE, EK3_SRCn_POSXY 6) looks like the natural fit and
# CANNOT WORK HERE. AP_VisualOdom.h sets AP_VISUALODOM_TIMEOUT_MS to 300, so visual
# odometry is "healthy" only while messages arrive more often than every 300 ms - better
# than 3.3 Hz, sustained. An Iridium Doppler solution needs an observation arc across a
# satellite pass and lands at roughly 1 Hz. It can never keep VisOdom healthy, so the
# aircraft would not arm, and would flap in and out of healthy if it somehow did.
#
# AP_GPS.cpp sets GPS_TIMEOUT_MS to 4000. A GPS may go quiet for four seconds. That is
# more than 13x the tolerance, and it comfortably accommodates a 1 Hz fix.
#
# So: GPS2_TYPE 14 (MAV), and the companion sends GPS_INPUT with global lat/lon. This is
# simpler in every direction - no EKF origin to track on the Pi, no NED conversion, no
# VISO_TYPE, and RTL and waypoints work natively because the position is absolute.
#
# GPS_AUTO_SWITCH 1 (UseBest) then gives AUTOMATIC failover: when the real receiver is
# jammed or denied its fix status drops, and ArduPilot moves to the SoOP instance with no
# pilot action at all. To force the SoOP instance for testing, set GPS_AUTO_SWITCH 0 and
# GPS_PRIMARY 1.
#
# The name is GPS2_TYPE, not GPS_TYPE2. ArduPilot renamed the GPS parameters in 4.6
# (AP_GPS.cpp:280-285 registers the instances as subgroups "1_" and "2_"), and BOTH
# spellings still appear in the generated metadata because the old ones are kept as
# conversion aliases for ground stations. So a metadata check passes the old name while
# the firmware silently refuses to set it - which is exactly what happened here, and is
# why sitl/check_params_live.py now reads every parameter back from a running build.
#
# SHIPS DISABLED, like everything else that is not soldered to the board: 0 until the
# companion is fitted and streaming. See docs/SENSORS.md.
