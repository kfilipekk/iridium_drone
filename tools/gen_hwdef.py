# ACTION 0 avoids the t+78 cancellation. The reason originally given here was "because
# the applet restores the prior mode (DR_NEXT_MODE -1)". THAT REASON IS RETIRED: -1 is
# no longer shipped (see the DR_NEXT_MODE block, which measured it oscillating) and it
# was never actually in effect anyway. The real reason is simpler and does not depend on
# the applet's next-mode choice at all: on ACTION 0 the failsafe ANNUNCIATES AND TAKES NO
# ACTION, so there is no cancellation to undo. Hence 0.
#
