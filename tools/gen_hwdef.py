# --- proximity / obstacle avoidance ---------------------------------------
# NOTHING IS SHIPPED HERE, DELIBERATELY, AND THAT IS A SAFETY CHOICE.
#
# The 360 lidar is an OFF-BOARD add-on. Enabling the backend before the hardware exists
# does not degrade gracefully - it grounds the aircraft. Measured in sitl/ scenario
# `proximity_absent`:
#
#     PRX1_TYPE 2, nothing sending OBSTACLE_DISTANCE  ->  "Arm: PRX1: No Data"
#
# So PRX1_TYPE stays 0 until the lidar is wired AND spinning. Same matched-set rule as
# FLOW_TYPE/EK3_SRC*_VELXY and RNGFND*_TYPE/EK3_SRC*_POSZ: a backend enable and the thing
# that feeds it are set together or not at all. This board has now been caught by that
# rule four separate times.
#
# TO FIT THE LDROBOT LD06 (2026-09-04 decision - it replaced the 8x VL53L1X ring and its
# TCA9548A mux, which needed MCU firmware nobody had written):
#
#     PRX1_TYPE 16          AP_Proximity_LD06 - 47-byte frame, 0x54 start, CRC8 0x4D
#     SERIAL2_PROTOCOL 11   Lidar360, on TP5 / TP6 (USART1)
#     SERIAL2_BAUD 230       230400.  An LD14P is 115200 instead - check the part
#
# Wire the lidar's TX only; leave the PWM motor input unconnected and it self-spins.
# INDOOR USE ONLY: the LD06 is rated 25 klux against ~100 klux full sun. Outdoors it
# reports phantom obstacles and AC_Avoid then brakes for nothing, which is worse than no
# sensor at all. Room lighting is 300-500 lux, so indoors it has ~50x of margin.
#
# WHAT THE LIDAR IS AND IS NOT. It is OBSTACLE AVOIDANCE - AC_Avoid stops the aircraft
# before a wall. IT IS NOT A POSITION SOURCE, and this is architectural: PRX1 feeds
# AP_Proximity -> AC_Avoid and never reaches the EKF. EK3_SRC*_POSXY accepts only
# 0=None, 3=GPS, 4=Beacon, 5=OpticalFlow, 6=ExternalNav - there is no proximity entry.
#
# So with no GNSS, no optical flow and no external navigation, the aircraft has NO
# horizontal position estimate indoors: Loiter, PosHold, RTL and Auto are unavailable and
# it flies Stabilize/AltHold under a pilot, with the lidar as a safety envelope. That is
# a deliberate, recorded choice - see docs/SENSORS.md for why ranging off walls does not
# substitute for flow, and what the SLAM route would actually cost.

