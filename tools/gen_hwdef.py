# --- failsafes ------------------------------------------------------------
# This file shipped NO FS_* parameters at all. On an ordinary GPS aircraft ArduPilot's
# own defaults are right; this aircraft is deliberately not one, and SITL showed what
# that costs. From sitl/ scenario `ekf_failsafe`, on the shipped configuration:
#
#     t+40s  GPS DENIED
#     t+55s  EKF Failsafe: changed to Land Mode
#     t+55s  MODE GUIDED -> LAND
#     t+56s  EKF Failsafe Cleared
#
# Fifteen seconds after GNSS denial the aircraft put itself into LAND - on exactly the
# mission this board exists to fly. Worse, the failsafe CLEARED one second later and the
# aircraft stayed in LAND, because ArduPilot does not restore the previous mode: a
# one-second variance transient commits it to landing permanently.
#
# Three settings were MEASURED, not argued about. All three still fire the failsafe:
#
#   FS_EKF_THRESH 0.8 (stock), ACTION 1   t+55s  -> LAND
#   FS_EKF_THRESH 1.0,         ACTION 1   t+55s  -> LAND        (threshold changed nothing)
#   FS_EKF_THRESH 1.0,         ACTION 2   t+72s  -> ALT_HOLD
#
# The threshold is NOT the lever. Relaxing it from 0.8 to 1.0 produced identical
# behaviour, which says the trip is not a slow drift over a variance limit - it is a
# TRANSIENT at the GPS1 -> GPS2 handover, and it clears within about two seconds either
# way. What matters is what the aircraft does in those two seconds, and ArduPilot never
# restores the previous mode afterwards.
#
# ACTION 2 (AltHold) WAS TRIED AND IS DANGEROUS HERE. It looked like the better answer -
# AltHold is recoverable where Land is not - and the rc_loss scenario then caught what
# that costs. AltHold is a PILOT mode, and the aircraft loses its pilot:
#
#   FS_EKF_ACTION 2, rc_loss:
#     t+58s  MODE GUIDED -> ALT_HOLD      EKF failsafe
#     t+70s  RC CUT (mode was ALT_HOLD)
#     t+70s  Disarming motors             <-- DISARMED IN FLIGHT, at 12 m
#     t+73s  PreArm: Radio failsafe on
#
#   FS_EKF_ACTION 1, same scenario:
#     t+70s  RC CUT   MODE LAND -> RTL    flies home
#
# Losing the radio while in AltHold disarms the aircraft, so action 2 is off the table.
# The choice is then between 1 (stock failsafe lands) and 0 (the dead-reckon applet owns
# GPS loss instead). That was decided by running BOTH, changing nothing else:
#
#   FS_EKF_ACTION 1, rc_loss:                 FS_EKF_ACTION 0 + DR_ENABLE 1, rc_loss_dr:
#     t+70s  RC CUT (mode GUIDED)               t+53s  MODE GUIDED -> GUIDED_NOGPS
#     t+70s  MODE GUIDED -> RTL                 t+58s  MODE GUIDED_NOGPS -> RTL
#     t+78s  MODE RTL -> LAND   <-- cancelled   t+70s  RC CUT (mode was RTL)
#     t+103s ground at 0.64 m/s                 t+94s  ground at 0.73 m/s
