# --------------------------------------------------------- IMU orientation ---
# MatekH743 mounts its primary IMUs on the top side; the packer put ours on the
# bottom to make the density work. A part on the far side of the board is the
# top-side placement composed with a 180 deg rotation about the board Y axis, so
# the rotation MatekH743 declares is wrong for this board by exactly that much.
# Left uncorrected the vehicle flies inverted, so this is derived from the actual
# PCB rather than written down and hoped for.
#
# ArduPilot applies its rotations roll, then pitch, then yaw (AP_Math/rotations.h).

def _rot(roll, pitch, yaw):
    import math
    def mul(A, B):
        return [[sum(A[i][k] * B[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    def R(axis, d):
        c, s = round(math.cos(math.radians(d))), round(math.sin(math.radians(d)))
        return {"x": [[1, 0, 0], [0, c, -s], [0, s, c]],
                "y": [[c, 0, s], [0, 1, 0], [-s, 0, c]],
                "z": [[c, -s, 0], [s, c, 0], [0, 0, 1]]}[axis]
    return mul(R("z", yaw), mul(R("y", pitch), R("x", roll)))

# The subset of ArduPilot's enum reachable by flipping a yaw-only placement.
_NAMED = {"NONE": (0, 0, 0), "YAW_90": (0, 0, 90), "YAW_180": (0, 0, 180),
          "YAW_270": (0, 0, 270), "ROLL_180": (180, 0, 0),
          "ROLL_180_YAW_90": (180, 0, 90), "PITCH_180": (0, 180, 0),
          "ROLL_180_YAW_270": (180, 0, 270)}
_MATRIX = {n: _rot(*rpy) for n, rpy in _NAMED.items()}


def flipped_rotation(name):
    """ROTATION_<name> as declared for a top-side part, corrected for bottom-side."""
    m = _rot(0, 180, 0)
    t = _MATRIX[name]
    got = [[sum(m[i][k] * t[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    for n, R in _MATRIX.items():
        if all(got[i][j] == R[i][j] for i in range(3) for j in range(3)):
            return n
    raise SystemExit(f"flipping ROTATION_{name} is not a named ArduPilot rotation")


def imu_sides(pcb):
    """{reference: True if on the bottom} straight out of the PCB."""
    import pcbnew
    b = pcbnew.LoadBoard(pcb)
    return {f.GetReference(): f.IsFlipped() for f in b.GetFootprints()}


def _wrap(text, width=76):
    words, line, out = text.split(), "", []
    for w in words:
        if len(line) + len(w) + 1 > width:
            out.append(line); line = w
        else:
            line = f"{line} {w}".strip()
    if line:
        out.append(line)
    return out


def main():
    src = open(REF).read().split("\n")
    out, dropped, rotated, replaced = [], [], [], []
    SIDE = imu_sides(PCB)
    IMU_REF = {"icm42688": "U2", "icm42605": "U3"}
    for ln in src:
        hit = next((why for pat, why in DROP if re.match(pat, ln)), None)
        if hit:
            dropped.append((ln.strip(), hit))
            out.append(f"# [removed: {hit}] {ln}")
            continue
        rep = next((r for r in REPLACE if re.match(r[0], ln)), None)
        if rep:
            _pat, new, why = rep
            out.append(f"# [was: {ln.strip()}]")
            for chunk in _wrap(why):
                out.append(f"# {chunk}")
            out.append(new)
            replaced.append((ln.strip(), new))
            continue
        if ln.startswith("APJ_BOARD_ID"):
            out.append(f"APJ_BOARD_ID AP_HW_NAVCORE_SOOP    # {BOARD_ID}, unregistered")
            continue
        if ln.startswith("# for Matek H743-WING"):
            out.append("# for NAVCORE-SoOP (45 x 46 mm, 30.5 mm stack)")
            continue
        m = re.match(r'^IMU (\S+) (?:\w+:)?(\S+) ROTATION_(\S+)\s*$', ln)
        if m and IMU_REF.get(m.group(2)) and SIDE.get(IMU_REF[m.group(2)]):
            was = m.group(3)
            now = flipped_rotation(was)
            ref = IMU_REF[m.group(2)]
            out.append(f"IMU {m.group(1)} SPI:{m.group(2)} ROTATION_{now}"
                       f"    # {ref} is on the bottom: was ROTATION_{was} on MatekH743")
            rotated.append((ref, m.group(2), was, now))
            continue
        out.append(ln)

    body = HEADER + "\n".join(out) + EXTRA + REVB
    os.makedirs(OUT, exist_ok=True)
    open(f"{OUT}/hwdef.dat", "w").write(body)

    bl = open(REFBL).read()
    bl = re.sub(r'^APJ_BOARD_ID.*$',
                f"APJ_BOARD_ID AP_HW_NAVCORE_SOOP    # {BOARD_ID}, unregistered",
                bl, flags=re.M)
    bl = bl.replace("# for Matek H743-WING bootloader",
                    "# for NAVCORE-SoOP bootloader")
    bl = bl.replace("PB12 MAX7456_CS CS",
                    "# [removed: no analogue OSD fitted] PB12 MAX7456_CS CS")
    open(f"{OUT}/hwdef-bl.dat", "w").write(
        "# GENERATED by tools/gen_hwdef.py - do not hand-edit.\n" + bl)
    open(f"{OUT}/defaults.parm", "w").write(defaults_parm())

    print(f"wrote {OUT}/hwdef.dat, hwdef-bl.dat and defaults.parm")
    print(f"board id: AP_HW_NAVCORE_SOOP = {BOARD_ID} (unregistered)")
    print(f"lines removed from the reference: {len(dropped)}")
    for ln, why in dropped:
        print(f"   {ln[:44]:<46} {why}")
    print(f"lines rewritten for this board's hardware: {len(replaced)}")
    for was, now in replaced:
        print(f"   {was[:44]:<46} -> {now}")
    print(f"IMU rotations corrected for bottom-side mounting: {len(rotated)}")
    for ref, dev, was, now in rotated:
        print(f"   {ref} {dev:<10} ROTATION_{was} -> ROTATION_{now}")


if __name__ == "__main__":
    main()
