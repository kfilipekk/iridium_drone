def load_scenarios():
    """Read the scenarios dict without importing scenarios.py."""
    src = (REPO / "sitl" / "scenarios.py").read_text()
    for node in ast.parse(src).body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and getattr(node.targets[0], "id", None) == "SCENARIOS"):
            return eval(compile(ast.Expression(node.value), "<scenarios>", "eval"),
                        {"__builtins__": {"dict": dict}}, {})
    raise SystemExit("FAIL: no SCENARIOS assignment in sitl/scenarios.py")


def kind(v):
    if v.get("expect_arm_failure"):
        return "must FAIL to arm"
    if v.get("dr_scenario"):
        return "pass/fail on applet mode transitions"
    if v.get("expect_mode"):
        return f"pass/fail: aircraft in {v['expect_mode']}"
    if v.get("watch_ekf"):
        return "pass/fail: failsafe must annunciate without acting"
    if v.get("expect_error_near"):
        return "canary - must report the injected offset"
    if v.get("harness_defect"):
        return "known harness defect, recorded not asserted"
    if v.get("expect_blocked_within") is not None or v.get("expect_ceiling") is not None:
        return "pass/fail"
    if v.get("informational"):
        return "informational - no pass/fail"
    if v.get("max_p95") is not None:
        return f"pass/fail, p95 <= {v['max_p95']:g} m"
    return "informational - no pass/fail"


def table(scen):
    rows = ["| Name | What it does | How it is judged |", "|---|---|---|"]
    for name, v in scen.items():
        first = v["why"].split(".")[0].strip().replace("|", "/")
        rows.append(f"| `{name}` | {first} | {kind(v)} |")
    n_info = sum(1 for v in scen.values() if kind(v).startswith("informational"))
    rows += [
        "",
        f"{len(scen)} scenarios; {n_info} are informational by design and "
        f"{len(scen) - n_info} can fail. `flow_only`, `extnav_1hz` and `soop_raw_1hz` "
        "are expected to look bad - a suite where everything passes by construction "
        "measures nothing.",
        "",
        "`./sitl/run_scenarios.sh --list` prints the full rationale for each. "
        "This table is generated by `tools/gen_scenario_table.py`; do not edit it here.",
    ]
    return "\n".join(rows)


