def spatial_table():
    """What the 3D assembly actually computes, so the record cannot drift from it."""
    sys.path.insert(0, str(REPO / "tools"))
    import design, math
    s = load_standoff()
    F, P, C, S, B = design.FRAME, design.PROP, design.CAMERA, design.SKID, design.BATT
    motor_off = F["wb"] / 2 / math.sqrt(2)
    prop_gap = motor_off * 2 - P["dia_mm"]
    cam_margin = S["drop"] + S["t"] - C["mod_t"] - C["lens_len"]
    rows = [
        ("stack height", f"**{s['below']+s['stack']:.1f} mm** "
         f"({s['below']:.1f} frame + {s['stack']:.1f} stack)",
         f"needs a **{s['buy']} mm** standoff; the kit's {F['inner_h']:.0f} mm is "
         f"{s['need']-F['inner_h']:.1f} mm short"),
        ("clearance above the FC", f"{s['buy']-s['below']-s['stack']:.1f} mm",
         f"to the top plate, tallest part `{s['topref']}`"),
        ("FC/ESC mounting", f"{design.MOUNTING['pitch']} x {design.MOUNTING['pitch']} mm",
         "shared pattern, boards concentric"),
        ("board envelope", "45.10 x 46.10 mm",
         f"{F_CAD_W:.2f} mm clear per side, {F_CAD_L:.2f} mm at the nearer end"),
        ("motor pattern", design.MOTOR["holes"], "[D] BrotherHobby product data"),
        ("propeller diameter", f"{P['dia_mm']:.1f} mm", "7 in"),
        ("adjacent propeller gap", f"**{prop_gap:.1f} mm**",
         f"{F['wb']:.0f} mm wheelbase, discs {motor_off*2:.1f} mm apart"),
        ("camera lens to skid contact", f"{cam_margin:.1f} mm",
         f"{S['drop']:.0f} mm drop + {S['t']:.1f} mm pad - {C['mod_t']:.0f} mm module "
         f"- {C['lens_len']:.1f} mm barrel; drop and thickness are [A]"),
        ("battery envelope", f"{B['L']} x {B['W']} x {B['H']} mm",
         "plan view only - restraint and CG are physical checks"),
        ("companion board", "NOT FITTED",
         "65 x 30 mm Radxa vs a 47 mm battery on a 50 mm plate - see docs/SENSORS.md"),
    ]
    out = ["| feature | value | note |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    out.append("")
    out.append("Interference is not asserted here: `tools/check_cad_fit.py` exports every "
               "part of `cad/drone.scad` and measures the **intersection volume** of all "
               f"{npairs()} pairs, plus their minimum separation.")
    return "\n".join(out)


def stack_table():
    """Every level of the stack, computed from the board and design.py."""
    sys.path.insert(0, str(REPO / "tools"))
    import design
    s = load_standoff()
    F, E, M = design.FRAME, design.ESC, design.MOUNTING
    z = 0.0
    rows = [["level", "height", "source"], ["---", "---", "---"]]
    def step(name, dz, src):
        nonlocal z
        z += dz
        rows.append([name, f"{z:.2f} mm", src])
    fsrc = F["src"].split(";")[0]
    step("top of the bottom plate", F["bottom_t"], fsrc)
    step("top of the arms", F["arm_t"], fsrc)
    step("top of the mid plate - **the stack bolts here**", F["medium_t"], fsrc)
    step("top of the ESC's PCB", E["pcb"], E["src"])
    step("top of the ESC's tallest part", E["parts"], E["src"])
    step(f"bottom of this board's tallest bottom part (`{s['botref']}`)",
         M["gap"], M["src"])
    step("underside of this board's PCB", s["bot"], "[M] board")
    step("top surface of this board", design.BOARD_T, "[D] 6-layer stackup from JLCPCB")
    step(f"top of the tallest part (`{s['topref']}`)", s["top"], "[M] board")
    rows.append([f"**standoff to buy - {s['buy']} mm**", f"{s['buy']:.2f} mm", s["src"]])
    rows.append(["**SPARE**", f"{s['buy'] - z:.2f} mm", "[M] derived"])
    return "\n".join("| " + " | ".join(r) + " |" for r in rows)


