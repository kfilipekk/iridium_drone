def module_table():
    """The modularity map, from design.MODULES."""
    sys.path.insert(0, str(REPO / "tools"))
    import design
    mods = {k: v for k, v in design.MODULES.items() if isinstance(v, dict)}
    now = {k: v for k, v in mods.items() if v["needs_board_change"] is None}
    later = {k: v for k, v in mods.items() if v["needs_board_change"] is not None}

    out = [f"**{len(now)} of {len(mods)} modules attach to the board exactly as it will be "
           "fabricated.** No respin, no cut traces, no adapter board.", "",
           "| module | what | attaches to | status | £ |", "|---|---|---|---|---|"]
    for k, m in sorted(now.items(), key=lambda kv: (kv[1]["status"] != "fitted", kv[0])):
        out.append(f"| `{k}` | {m['what']} | {m['conn']} | {m['status']} | {m["gbp"]} |")

    out += ["", f"### The {len(later)} that would need a second fabrication run", "",
            "Neither is on the critical path, and neither blocks a capability outright:",
            "", "| module | what a respin would have to change | why it is not urgent |",
            "|---|---|---|"]
    for k, m in sorted(later.items()):
        out.append(f"| `{k}` | {m['needs_board_change']} | {m['note']} |")
    rail = design.RAIL_5V
    budget = rail["headroom_a"] * 1000
    unc = sorted(((n, m["ma_5v"]) for n, m in mods.items()
                  if not m["counted"] and m["ma_5v"]), key=lambda x: -x[1])
    tot = sum(ma for _, ma in unc)
    out += ["", "### They attach. They cannot all run at once.", "",
            f"Attaching and powering are different questions, and the +5 V rail answers the "
            f"second one more strictly. `L2` is rated **{rail['irms_a']} A RMS** and the "
            f"fully-fitted load in `check_build.LOADS_5V` is already "
            f"**{rail['fitted_load_a']:.3f} A**, leaving **{budget:.0f} mA**:", "",
            "| module not yet in that budget | draw |", "|---|---|"]
    out += [f"| `{n}` | {ma} mA |" for n, ma in unc]
    out += [f"| **total** | **{tot} mA** |", "",
            f"**{tot} mA offered against {budget:.0f} mA available.** Fit one or two, or give "
            "one its own BEC off the battery — which is the right answer for anything with "
            "real transients anyway. This is a **power** limit, not an interface limit: every "
            "module above still lands on a real pad.", "",
            "Generated by `tools/gen_doc_tables.py` from `design.MODULES` and "
            "`design.RAIL_5V`; do not edit it here."]
    return "\n".join(out)


def fastener_tables():
    """Whatever `fasteners.py --md` prints, verbatim."""
    r = subprocess.run([sys.executable, str(REPO / "tools" / "fasteners.py"), "--md"],
                       capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        raise SystemExit(f"FAIL: fasteners.py --md exited {r.returncode}\n{r.stderr}")
    return (r.stdout.strip() + "\n\nGenerated by `tools/gen_doc_tables.py` from "
            "`tools/fasteners.py`; do not edit it here.")


def order_sheet():
    """The shopping list, generated from docs/PARTS.csv rather than hand-written."""
    import csv
    rows = list(csv.DictReader(open(REPO / "docs" / "PARTS.csv")))
    cost_key = next(k for k in rows[0] if "USD" in k or "Indicative" in k)
    buy = [r for r in rows if r["Status"].strip() in ("TO BUY", "BUY")]
    later = [r for r in rows if r["Status"].strip() in ("LATER", "DEFERRED", "CONSIDER")]

    def money(r):
        try:
            return float(r[cost_key] or 0)
        except ValueError:
            return 0.0

    TIER = {"Indoor avoidance": 2, "Navigation": 2, "Tools": 3, "Notify": 3,
            "SoOP receiver": 4}
    NAMES = {1: "Minimum to fly", 2: "Sensors - optional for first flight",
             3: "Tools and bench kit - buy once",
             4: "SoOP receiver - proves the thesis, needs no board respin"}

    def tier(r):
        return TIER.get(r["Group"].strip(), 1)

    def tag_of(r):
        s = r["Provenance"].strip()
        return ("**[A]**" if s.startswith("ASSUMED") else
                "[D]" if s.startswith(("DATASHEET", "[D]")) else
                "[L]" if s.startswith(("LISTING", "[L]")) else
                "[M]" if s.startswith(("MEASURED", "[M]")) else "[?]")

    def price_tag(r):
        """Whether the price is quoted or guessed - a different question from whether the
        spec is verified, and previously conflated with it. A link to a search page
        means the number beside it is an estimate nobody has checked against a real
        listing.
        """
        u = r["Link"].strip()
        return "~est" if ("/w/" in u or "wholesale" in u or u in ("-", "")) else "quoted"

    out, total, n = [], 0.0, 0
    subtotals = {}
    for tn in (1, 2, 3, 4):
        grp = [r for r in buy if tier(r) == tn]
        if not grp:
            continue
        sub = sum(money(r) for r in grp)
        subtotals[tn] = sub
        total += sub
        out += [f"**Tier {tn} — {NAMES[tn]}** — {len(grp)} lines, ~GBP {sub:.0f}", "",
                "| # | item | qty | ~GBP | price | source | spec |",
                "|---|---|---:|---:|---|---|---|"]
        for r in grp:
            n += 1
            out.append(f"| {n} | {r['Item']} | {r['Qty']} | {money(r):.0f} | "
                       f"{price_tag(r)} | {r['Source']} | {tag_of(r)} |")
        out.append("")
    out += [f"**TOTAL {len(buy)} lines, ~GBP {total:.0f}.** "
            + " ".join(f"Tier {k} ~GBP {v:.0f}." for k, v in sorted(subtotals.items())),
            "",
            f"**Cheapest path to a flying aircraft is Tier 1 alone: ~GBP "
            f"{subtotals.get(1, 0):.0f}.** Tier 2 is the ToF/lidar sensor suite, which "
            "nothing in Tier 1 depends on - `PRX1_TYPE` and every `RNGFNDn_TYPE` ship at "
            "0, so the aircraft flies without them and does not even notice they are "
            "absent. Tier 3 you buy once and keep.", "",
            "Two separate columns, because they are two separate questions. **price** "
            "`quoted` means the link goes to a real product listing; `~est` means it goes "
            "to a search page and the number beside it is an estimate nobody has checked. "
            "**spec** **[A]** means the part's specification is assumed rather than "
            "sourced. A line can be quoted-but-assumed or estimated-but-datasheeted; "
            "conflating them hides which number to go and verify.",
            "",
            "`tools/check_purchase.py` asserts every interface between two of these parts "
            "and names the ones still resting on an assumed source.",
            ""]
    if later:
        out += [f"Held back ({len(later)}): "
                + ", ".join(f"{r['Item']} (~GBP {money(r):.0f})" for r in later), ""]
    out.append("Generated from `docs/PARTS.csv` by `tools/gen_doc_tables.py`; do not edit "
               "it here. Change a part's `Status` in the CSV to move it in or out.")
    return "\n".join(out)


def _splice(path, begin, end, body, what, check):
    text = path.read_text()
    if begin not in text or end not in text:
        print(f"FAIL: {path} has no {begin} / {end} markers")
        return 1, text
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    new = f"{head}{begin}\n{body}\n{end}{tail}"
    if new == text:
        print(f"{what} is current")
        return 0, text
    if check:
        print(f"FAIL: {path.name} {what} is stale - run tools/gen_doc_tables.py")
        return 1, text
    path.write_text(new)
    print(f"rewrote the {what} in {path}")
    return 0, new


def cross_doc_totals(check):
    """docs/BENCHMARK.md quotes the order total. Assert it against the generated one."""
    import csv as _csv, re as _re
    rows = list(_csv.DictReader(open(REPO / "docs" / "PARTS.csv")))
    def _money(r):
        v = (r.get("Indicative USD (LINE TOTAL, not unit)") or "").strip()
        try: return float(_re.sub(r"[^0-9.]", "", v) or 0)
        except ValueError: return 0.0
    total = round(sum(_money(r) for r in rows
                      if (r.get("Status") or "").strip().upper() == "TO BUY"))
    txt = (REPO / "docs" / "BENCHMARK.md").read_text()
    m = _re.search(r'\*\*GBP\s*([\d,]+) airframe', txt) or \
        _re.search(r'\*\*\u00a3([\d,]+) airframe', txt)
    if not m:
        print("  cross-doc totals: no airframe cost figure found in BENCHMARK.md")
        return 1
    quoted = int(m.group(1).replace(",", ""))
    if quoted == total:
        print(f"  cross-doc totals: BENCHMARK.md airframe cost {quoted} matches "
              f"the generated order sheet")
        return 0
    print(f"  cross-doc totals: BENCHMARK.md says {quoted} but PARTS.csv 'TO BUY' "
          f"sums to {total}" + ("" if check else " - FIX IT BY HAND, this is prose"))
    return 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rc = 0
    rc |= _splice(REPO / "sitl" / "README.md", SCEN_BEGIN, SCEN_END,
                  table(load_scenarios()), "scenario table", args.check)[0]
    rc |= _splice(REPO / "docs" / "HARDWARE.md", FRAME_BEGIN, FRAME_END,
                  frame_table(load_frame()), "frame table", args.check)[0]
    rc |= _splice(REPO / "docs" / "BUYING.md", SPATIAL_BEGIN, SPATIAL_END,
                  spatial_table(), "spatial table", args.check)[0]
    rc |= _splice(REPO / "docs" / "HARDWARE.md", STACK_BEGIN, STACK_END,
                  stack_table(), "stack table", args.check)[0]
    rc |= _splice(REPO / "docs" / "HARDWARE.md", FAST_BEGIN, FAST_END,
                  fastener_tables(), "fastener table", args.check)[0]
    rc |= _splice(REPO / "docs" / "MODULES.md", MODULE_BEGIN, MODULE_END,
                  module_table(), "module table", args.check)[0]
    rc |= _splice(REPO / "docs" / "BUYING.md", ORDER_BEGIN, ORDER_END,
                  order_sheet(), "order sheet", args.check)[0]
    rc |= cross_doc_totals(args.check)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
